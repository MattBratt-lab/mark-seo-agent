/**
 * Point Wrangler + Pages Functions at your REAL static site root:
 *   node scripts/sync-functions-for-static-site.mjs "/absolute/path/to/site-root"
 *
 * Copies seo-scraper-site-reference/functions, regenerates _valid-paths.ts from that tree,
 * writes _404-html.ts from ${siteRoot}/404.html or a minimal stub.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, "..");
const functionsSrc = path.join(repoRoot, "seo-scraper-site-reference", "functions");

const SKIP_DIRS = new Set([
  ".git",
  "node_modules",
  "functions",
  "dist",
  ".wrangler",
  "venv",
  ".venv",
  "agents",
  "backend",
  "data",
]);

function collectValidPathnames(siteRoot) {
  const paths = new Set();

  function walk(relPosix) {
    const readDir = relPosix === "." ? siteRoot : path.join(siteRoot, relPosix.split("/").join(path.sep));
    if (!fs.existsSync(readDir)) return;
    for (const ent of fs.readdirSync(readDir, { withFileTypes: true })) {
      if (ent.isDirectory() && SKIP_DIRS.has(ent.name)) continue;
      const childRel = relPosix === "." ? ent.name : `${relPosix}/${ent.name}`;
      const posix = childRel.replace(/\\/g, "/");
      if (ent.isDirectory()) {
        walk(posix);
      } else if (posix === "index.html") {
        paths.add("/");
        paths.add("/index.html");
      } else if (posix.endsWith("/index.html")) {
        const dir = posix.slice(0, -"/index.html".length);
        const base = "/" + dir;
        paths.add(base);
        paths.add(base + "/");
      } else {
        if (posix.endsWith(".gitkeep") || posix.split("/").some((seg) => seg.startsWith("_"))) {
          continue;
        }
        paths.add("/" + posix);
      }
    }
  }

  walk(".");
  return Array.from(paths).sort();
}

function copyRecursive(src, dest) {
  fs.cpSync(src, dest, { recursive: true });
}

function main() {
  const siteRoot = process.argv[2];
  if (!siteRoot || !fs.statSync(siteRoot).isDirectory()) {
    console.error("Usage: node scripts/sync-functions-for-static-site.mjs /absolute/path/to/site-root");
    process.exit(1);
  }

  if (!fs.existsSync(functionsSrc)) {
    console.error(`Missing ${functionsSrc}`);
    process.exit(1);
  }

  const destFn = path.join(siteRoot, "functions");
  if (fs.existsSync(destFn)) fs.rmSync(destFn, { recursive: true, force: true });
  copyRecursive(functionsSrc, destFn);

  const pathnames = collectValidPathnames(siteRoot);
  const pathLines = pathnames.map((p) => `  ${JSON.stringify(p)}`).join(",\n");
  const validPathsTs = `/** Auto-generated by scripts/sync-functions-for-static-site.mjs — do not edit. */

const VALID = new Set<string>([
${pathLines}
]);

export function isValidPathname(pathname: string): boolean {
  if (VALID.has(pathname)) return true;
  try {
    const decoded = decodeURIComponent(pathname);
    if (decoded !== pathname && VALID.has(decoded)) return true;
  } catch {
    /* ignore malformed escapes */
  }
  return false;
}
`;
  fs.writeFileSync(path.join(destFn, "_valid-paths.ts"), validPathsTs, "utf8");

  const notFoundPath = path.join(siteRoot, "404.html");
  const notFoundHtml = fs.existsSync(notFoundPath)
    ? fs.readFileSync(notFoundPath, "utf8")
    : "<!doctype html><html><head><meta charset=\"utf-8\"><title>Not found</title></head><body><h1>404</h1></body></html>";
  const notFoundTs = `/** Auto-generated by scripts/sync-functions-for-static-site.mjs — do not edit. */

export const NOT_FOUND_HTML: string = ${JSON.stringify(notFoundHtml)};
`;
  fs.writeFileSync(path.join(destFn, "_404-html.ts"), notFoundTs, "utf8");

  const wranglerSrc = path.join(repoRoot, "seo-scraper-site-reference", "wrangler.toml");
  if (fs.existsSync(wranglerSrc)) {
    fs.copyFileSync(wranglerSrc, path.join(siteRoot, "wrangler.toml"));
  }

  console.log(`Synced Pages Functions → ${destFn}`);
  console.log(`Wrote _valid-paths.ts (${pathnames.length} pathnames)`);
  console.log(`Copied wrangler.toml (D1 binding \"DB\" → garage-db) → ${path.join(siteRoot, "wrangler.toml")}`);
  console.log(`Next: cd "${siteRoot}" && npx wrangler pages deploy . --project-name=db-garage-doors --branch=main --commit-dirty=true`);
}

main();
